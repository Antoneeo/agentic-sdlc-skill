def git_head(root):
    try:
        r = subprocess.run(["git", "rev-parse", "--short=12", "HEAD"],
                           cwd=str(root), capture_output=True, text=True, timeout=10)
        return r.stdout.strip() if r.returncode == 0 else ""
    except Exception:
        return ""


def git_has_changes(root, rel_path):
    """True if there are tracked/untracked changes under rel_path."""
    try:
        rel = rel_path.replace("\\", "/")
        r = subprocess.run(["git", "status", "--porcelain", "--", rel],
                           cwd=str(root), capture_output=True, text=True, timeout=30)
        return r.returncode == 0 and bool(r.stdout.strip())
    except Exception:
        return False


def git_changed_since(root, ref, rel_path):
    """Files changed (tracked + untracked) under rel_path since ref. None if ref unresolvable."""
    try:
        r = subprocess.run(["git", "diff", "--name-only", ref, "--", rel_path],
                           cwd=str(root), capture_output=True, text=True, timeout=30)
        if r.returncode != 0:
            return None
        changed = [l.strip() for l in r.stdout.splitlines() if l.strip()]
        r2 = subprocess.run(["git", "ls-files", "--others", "--exclude-standard", "--", rel_path],
                            cwd=str(root), capture_output=True, text=True, timeout=30)
        if r2.returncode == 0:
            changed += [l.strip() for l in r2.stdout.splitlines() if l.strip()]
        return sorted(set(changed))
    except Exception:
        return None


def git_ref_state(root, ref):
    """Where a recorded commit stands against HEAD (F-056).

    'ancestor' -- in HEAD's history; 'orphan' -- a commit HEAD's history does not
    contain (amended, rebased or squash-merged away, or marked on another branch:
    it stops resolving once pruned, and on any fresh clone); 'missing' -- not a
    commit in this repository; 'unknown' -- git gave no yes/no answer.
    Callers pass a hash-shaped ref only: that check is what keeps document
    content from reaching git's argv as an option."""
    try:
        r = subprocess.run(["git", "cat-file", "-e", ref + "^{commit}"],
                           cwd=str(root), capture_output=True, text=True, timeout=30)
        if r.returncode != 0:
            return "missing"
        r = subprocess.run(["git", "merge-base", "--is-ancestor", ref, "HEAD"],
                           cwd=str(root), capture_output=True, text=True, timeout=30)
    except Exception:
        return "unknown"
    return {0: "ancestor", 1: "orphan"}.get(r.returncode, "unknown")


def git_is_shallow(root):
    try:
        r = subprocess.run(["git", "rev-parse", "--is-shallow-repository"],
                           cwd=str(root), capture_output=True, text=True, timeout=10)
        return r.returncode == 0 and r.stdout.strip() == "true"
    except Exception:
        return False


