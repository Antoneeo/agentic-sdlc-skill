#!/usr/bin/env node
// "What's new" on the npm page (F-070): each package's README shows the
// `### What's new` of its own version's CHANGELOG section, between
// `<!-- whats-new:begin -->` and `<!-- whats-new:end -->`.
//
// Dev-only: absent from every package.json `files`. Run from the repository root:
//   node scripts/whats_new.js              check every package
//   node scripts/whats_new.js --write      regenerate the README regions
//   node scripts/whats_new.js --require D  also fail a package without notes
// Packages are the repository root and every distributions/* holding a
// package.json, unless directories are named. publish_all.bat runs `--require`
// on each package it is about to publish.

const fs = require('fs');
const path = require('path');
const region = require('./md_region');

const TITLE = "What's new";
const REGION = 'whats-new';
const REPO_URL = 'https://github.com/Antoneeo/agentic-sdlc-skill/blob/main/';

function discover(root) {
  const dist = path.join(root, 'distributions');
  const subs = fs.existsSync(dist)
    ? fs.readdirSync(dist).sort().map((d) => path.join(dist, d))
    : [];
  return [root].concat(subs).filter((d) => fs.existsSync(path.join(d, 'package.json')));
}

// relDir: the package's folder relative to the repository root, '' for the root.
function render(version, body, relDir) {
  const changelog = (relDir ? relDir.split(path.sep).join('/') + '/' : '') + 'CHANGELOG.md';
  return [
    `<!-- generated by scripts/whats_new.js from ${changelog}: edit the CHANGELOG, then run node scripts/whats_new.js --write -->`,
    `## What's new in ${version}`,
    '',
    body,
    '',
    `Full history: [CHANGELOG](${REPO_URL}${changelog})`,
  ].join('\n');
}

function one(root, dir, opts) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const who = `${pkg.name} ${pkg.version}`;
  const notes = region.extractSubsection(
    fs.readFileSync(path.join(dir, 'CHANGELOG.md'), 'utf8'), pkg.version, TITLE);
  if (notes.status === 'error') return [false, `[FAIL] ${who}: CHANGELOG.md ${notes.reason}`];
  if (notes.status === 'absent' && opts.require) {
    return [false, `[FAIL] ${who}: no "What's new" for ${pkg.version} in CHANGELOG.md - write it under "## [${pkg.version}]", then node scripts/whats_new.js --write`];
  }
  const content = notes.status === 'found' ? render(pkg.version, notes.body, path.relative(root, dir)) : '';
  const readme = path.join(dir, 'README.md');
  const r = opts.write
    ? region.writeRegion(readme, REGION, content)
    : region.syncRegion(fs.readFileSync(readme, 'utf8'), REGION, content);
  if (r.status === 'error') return [false, `[FAIL] ${who}: README.md ${r.reason}`];
  if (r.status === 'differs') {
    return [false, `[FAIL] ${who}: README.md disagrees with CHANGELOG.md - run node scripts/whats_new.js --write`];
  }
  return [true, `[ok] ${who}: README ${r.status === 'written' ? 'updated' : 'agrees'}`];
}

function run({ root, dirs, write = false, require: req = false, log = console.log }) {
  let ok = true;
  for (const dir of dirs && dirs.length ? dirs : discover(root)) {
    let result;
    try {
      result = one(root, path.resolve(dir), { write, require: req });
    } catch (e) {
      // An unreadable package is reported like any other failure; the rest still run.
      result = [false, `[FAIL] ${dir}: ${e.code ? `${e.code} ${e.path || ''}`.trim() : e.message}`];
    }
    ok = ok && result[0];
    log(result[1]);
  }
  return ok ? 0 : 1;
}

const USAGE = 'usage: node scripts/whats_new.js [--write] [--require] [--root <repo>] [<package dir> ...]';

if (require.main === module) {
  const argv = process.argv.slice(2);
  const opts = { root: path.resolve(__dirname, '..'), dirs: [] };
  let bad = null;
  for (let i = 0; i < argv.length && !bad; i += 1) {
    if (argv[i] === '--write') opts.write = true;
    else if (argv[i] === '--require') opts.require = true;
    else if (argv[i] === '--root' && argv[i + 1] && !argv[i + 1].startsWith('--')) opts.root = path.resolve(argv[(i += 1)]);
    else if (argv[i].startsWith('--')) bad = argv[i];
    else opts.dirs.push(argv[i]);
  }
  if (bad) {
    console.error(`[FAIL] ${bad === '--root' ? '--root needs a directory' : `unknown option ${bad}`}\n${USAGE}`);
    process.exitCode = 2;
  } else {
    process.exitCode = run(opts);
  }
}

module.exports = { discover, render, run };
