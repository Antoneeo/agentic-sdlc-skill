"""F-066 probe: which docs-root files are generated, and can a marker tell?

Run from the repository root:  python ai_docs/solutions/harness_merge_review/probe_generated.py

Claim A (RED for marker detection): classifying "generated" by the
`GENERATED by ... index` marker misses at least one file `index` writes.
Claim B (GREEN for execution): running the installed entry point's `index`
on a throwaway copy of the docs root, after zeroing every mtime, yields the
exact set of files the validator writes -- asserted as equality against
this repo's known outputs, so over- and under-inclusion both fail.
Exit 0 when both claims hold; 1 otherwise. Writes only under a temp dir.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ENTRY = ROOT / "skills" / "agentic-sdlc-skill" / "scripts" / "sdlc_check.py"
MARKER = re.compile(r"GENERATED by \S+ index - do not edit by hand")


def written_by_index(docs: Path) -> set:
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / docs.name
        shutil.copytree(docs, copy)
        for p in copy.rglob("*"):
            if p.is_file():
                os.utime(p, (0, 0))
        subprocess.run([sys.executable, str(ENTRY), "index", "--root", tmp],
                       check=True, capture_output=True)
        return {p.relative_to(copy).as_posix() for p in copy.rglob("*")
                if p.is_file() and p.stat().st_mtime > 0}


def marked(docs: Path, rels: set) -> set:
    # --negate is the red run: pretend every generated file carried the marker,
    # which must make claim A fail -- a probe that cannot fail proves nothing.
    if "--negate" in sys.argv:
        return set(rels)  # red run for A
    return {r for r in rels
            if MARKER.search("\n".join((docs / r).read_text(encoding="utf-8",
                                       errors="replace").splitlines()[:6]))}


def main():
    docs = ROOT / "ai_docs"
    written = written_by_index(docs)
    by_marker = marked(docs, written)
    missed = sorted(written - by_marker)
    print("written by index:", sorted(written))
    print("missed by marker:", missed)
    claim_a = bool(missed)
    expected = {"INDEX.md", "strategic/features_history.md", "reference/INDEX.md",
                "memory/INDEX.md", "audit/handoff.md"}  # this repo: HANDOFF sources exist
    if "--negate" in sys.argv:          # red run for B: one output the method must not miss
        expected = expected | {"vision/project_vision.md"}
    claim_b = written == expected
    print("A (marker misses a generated file):", "HOLDS" if claim_a else "FAILS")
    print("B (execution finds the known outputs):", "HOLDS" if claim_b else "FAILS")
    return 0 if claim_a and claim_b else 1


if __name__ == "__main__":
    sys.exit(main())
