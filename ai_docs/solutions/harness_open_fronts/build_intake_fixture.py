"""F-097 replay fixture, question 1: a project whose workstream registry is the
recorded one (case_registry_40.md of harness_honest_signals: 43 HANDOFF
frontmatters, 40 registry rows), into which a request for new work arrives.

Builds a throwaway project: a few lines of code, a minimal docs root, the 43
recorded frontmatters as HANDOFF files, the registry generated by the given
validator, and SESSION_START.txt holding what the session-start hook would inject
(`orient`). The scenario text is in replay_intake.md.

Usage: python build_intake_fixture.py <case_registry_40.md> <sdlc_check.py> <out dir>
       python build_intake_fixture.py --small <sdlc_check.py> <out dir>

`--small` builds the same project with three named workstreams instead of the
recorded forty: the fixture of the variant where the request belongs to a row
(FS3), which the redacted rows of the recorded case cannot carry.
"""
import re
import subprocess
import sys
from pathlib import Path

NL = chr(10)

VISION = """---
description: Why this service exists.
status: CURRENT
---
# Project Vision

Status: APPROVED

## North Star
A small internal service that keeps the customer list and lets staff read it.

## Actors
- Back-office staff - read and export the customer list.

## Goals
- Staff get the customer data they need without asking a developer.

## Non-Goals
- No public access.
"""

README = """---
default_domain: code
---
# ai_docs - reading guide

1. `vision/project_vision.md` - why the service exists.
2. `audit/handoff.md` - the workstream registry (generated).
"""

APP = '''"""Customer list service (fixture)."""
import json
from http.server import BaseHTTPRequestHandler, HTTPServer

CUSTOMERS = [{"id": 1, "name": "Ada"}, {"id": 2, "name": "Bo"}]


class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path == "/customers":
            body = json.dumps(CUSTOMERS).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(body)
        else:
            self.send_response(404)
            self.end_headers()


if __name__ == "__main__":
    HTTPServer(("127.0.0.1", 8000), Handler).serve_forever()
'''


SMALL = [
    ("invoice_pdf", "F-003 Invoice PDF", "IN_PROGRESS", "wire the totals test",
     "ANALYSIS_invoice_pdf.md"),
    ("login_audit", "F-005 Login audit trail", "PAUSED",
     "owner decides the retention period", "ANALYSIS_login_audit.md"),
    ("customer_csv_export", "F-007 Customer CSV export", "PLANNED",
     "independent design review of the analysis", "ANALYSIS_customer_csv_export.md"),
]


def small_blocks():
    out = []
    for slug, ws, status, nxt, details in SMALL:
        out.append((slug, NL.join([
            "---", f"workstream: {ws}", "level: L3", f"branch: feat/{slug}",
            f"status: {status}", "since: 2026-10-20", f"next: {nxt}",
            f"details: {details}", "updated: 2026-11-10", "---"])))
    return out


def frontmatters(case_text):
    section_b = case_text.split("## Sezione B", 1)[1]
    pattern = r"^### (Filone-\d+)[^\n]*\n+```yaml\n(---\n.*?\n---)\n```"
    return [(m.group(1), m.group(2)) for m in re.finditer(pattern, section_b, re.S | re.M)]


def main():
    checker, out = Path(sys.argv[2]).resolve(), Path(sys.argv[3])
    if sys.argv[1] == "--small":
        blocks = small_blocks()
    else:
        text = Path(sys.argv[1]).read_text(encoding="utf-8").replace("\r\n", NL)
        blocks = frontmatters(text)
        assert len(blocks) == 43, f"expected 43 frontmatters, parsed {len(blocks)}"
    docs = out / "ai_docs"
    for sub in ("audit", "vision", "solutions", "reference"):
        (docs / sub).mkdir(parents=True, exist_ok=True)
    (out / "app").mkdir(exist_ok=True)
    (out / "app" / "server.py").write_text(APP, encoding="utf-8")
    (docs / "README.md").write_text(README, encoding="utf-8")
    (docs / "vision" / "project_vision.md").write_text(VISION, encoding="utf-8")
    for label, block in blocks:
        name = f"HANDOFF_{label.replace('-', '_')}.md"
        (docs / "audit" / name).write_text(block + NL + "# HANDOFF" + NL, encoding="utf-8")
    subprocess.run(["git", "init", "-q", str(out)], check=False)
    subprocess.run([sys.executable, str(checker), "index", "--root", str(out)],
                   capture_output=True, text=True)
    res = subprocess.run([sys.executable, str(checker), "orient", "--root", str(out)],
                         capture_output=True, text=True, encoding="utf-8", errors="replace")
    (out / "SESSION_START.txt").write_text(res.stdout, encoding="utf-8")
    rows = sum(1 for line in (docs / "audit" / "handoff.md").read_text(
        encoding="utf-8").splitlines() if line.startswith(("| Filone-", "| F-0")))
    print(f"fixture at {out}: {len(blocks)} HANDOFF files, {rows} registry rows, "
          f"orientation {len(res.stdout)} chars")
    return 0


if __name__ == "__main__":
    sys.exit(main())
